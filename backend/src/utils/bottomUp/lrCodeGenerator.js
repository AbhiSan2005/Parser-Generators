/**
 * Generates standalone, exportable parser code.
 * Injects the compiled ACTION and GOTO tables directly into a JavaScript script.
 */
export const generateLRCode = (grammar, tableData, parserType) => {
    const { action, goto, indexed_rules } = tableData;

    // Convert matrices to strings for injection
    const actionStr = JSON.stringify(action, null, 4);
    const gotoStr = JSON.stringify(goto, null, 4);
    const rulesStr = JSON.stringify(indexed_rules, null, 4);
    const pythonAction = JSON.stringify(action, null, 4);
    const pythonGoto = JSON.stringify(goto, null, 4);
    const pythonRules = JSON.stringify(indexed_rules, null, 4);
    const cppQuote = (value) => JSON.stringify(String(value));
    const actionRows = Object.keys(action).sort((a, b) => Number(a) - Number(b));
    const gotoRows = Object.keys(goto).sort((a, b) => Number(a) - Number(b));
    const cppAction = actionRows.map(state => `    {{${Object.entries(action[state]).map(([symbol, value]) => `${cppQuote(symbol)}, ${cppQuote(value)}`).join('}, {')}}}`).join(',\n');
    const cppGoto = gotoRows.map(state => `    {{${Object.entries(goto[state]).map(([symbol, value]) => `${cppQuote(symbol)}, ${value}`).join('}, {')}}}`).join(',\n');
    const cppRules = indexed_rules.map(({ variable, rule }) => `    {${cppQuote(variable)}, {${rule.map(cppQuote).join(', ')}}}`).join(',\n');
    const cppTerminals = grammar.terminals.map(cppQuote).join(', ');

    // ==========================================
    // JAVASCRIPT STANDALONE TEMPLATE
    // ==========================================
    const javascriptCode = `// Autogenerated ${parserType} Parser
// Generated by Compiler Playground

const ACTION_TABLE = ${actionStr};
const GOTO_TABLE = ${gotoStr};
const RULES = ${rulesStr};

class Parser {
    constructor(terminals) {
        // Sort terminals by length descending to match longest tokens first
        this.terminals = terminals.sort((a, b) => b.length - a.length);
    }

    tokenize(input) {
        let cursor = 0;
        const tokens = [];
        
        while (cursor < input.length) {
            const char = input[cursor];
            
            // Skip whitespace
            if (/\\s/.test(char)) { 
                cursor++; 
                continue; 
            }
            
            let matched = false;
            for (const t of this.terminals) {
                if (input.startsWith(t, cursor)) {
                    tokens.push(t);
                    cursor += t.length;
                    matched = true;
                    break;
                }
            }
            if (!matched) throw new Error(\`Lexical Error: Unrecognized token at position \${cursor}\`);
        }
        
        tokens.push('$');
        return tokens;
    }

    parse(inputString) {
        const tokens = this.tokenize(inputString);
        const stateStack = [0];
        const symbolStack = [];
        let cursor = 0;

        while (cursor < tokens.length) {
            const state = stateStack[stateStack.length - 1];
            const lookahead = tokens[cursor];
            const action = ACTION_TABLE[state][lookahead];

            if (!action) {
                throw new Error(\`Syntax Error: Unexpected '\${lookahead}' at state \${state}\`);
            }

            if (action === 'acc') {
                console.log("✅ PARSE SUCCESSFUL!");
                return symbolStack[0];
            }

            // Shift
            if (action.startsWith('s')) {
                const nextState = parseInt(action.substring(1), 10);
                stateStack.push(nextState);
                symbolStack.push({ name: lookahead, children: [] });
                cursor++;
            } 
            // Reduce
            else if (action.startsWith('r')) {
                const ruleIdx = parseInt(action.substring(1), 10);
                const rule = RULES[ruleIdx];
                const popCount = rule.rule[0] === 'ε' ? 0 : rule.rule.length;
                
                const children = [];
                for (let i = 0; i < popCount; i++) {
                    stateStack.pop();
                    children.unshift(symbolStack.pop());
                }

                const exposedState = stateStack[stateStack.length - 1];
                const gotoState = GOTO_TABLE[exposedState][rule.variable];
                
                if (gotoState === undefined) {
                    throw new Error(\`GOTO Error: Missing transition for '\${rule.variable}'\`);
                }
                
                stateStack.push(gotoState);
                symbolStack.push({ name: rule.variable, children });
            }
        }
        
        throw new Error("Parse failed: Unexpected end of input.");
    }
}

// ==========================================
// EXAMPLE USAGE:
// Uncomment the lines below to test this file locally using Node.js
// ==========================================
// const parser = new Parser(${JSON.stringify(grammar.terminals)});
// try {
//     const ast = parser.parse("id + id"); // Replace with your test string
//     console.log(JSON.stringify(ast, null, 2));
// } catch (error) {
//     console.error(error.message);
// }
`;

    const pythonCode = `# Autogenerated ${parserType} Parser
import json
import sys

ACTION_TABLE = ${pythonAction}
GOTO_TABLE = ${pythonGoto}
RULES = ${pythonRules}
TERMINALS = ${JSON.stringify(grammar.terminals)}

class Parser:
    def tokenize(self, text):
        tokens = []
        cursor = 0
        terminals = sorted(TERMINALS, key=len, reverse=True)
        while cursor < len(text):
            if text[cursor].isspace():
                cursor += 1
                continue
            match = next((token for token in terminals if text.startswith(token, cursor)), None)
            if match is None:
                raise ValueError(f"Lexical error at position {cursor}")
            tokens.append(match)
            cursor += len(match)
        return tokens + ["$"]

    def parse(self, text):
        tokens = self.tokenize(text)
        state_stack = [0]
        symbol_stack = []
        cursor = 0
        while cursor < len(tokens):
            state = state_stack[-1]
            lookahead = tokens[cursor]
            action = ACTION_TABLE[str(state)].get(lookahead)
            if action is None:
                raise ValueError(f"Syntax error: unexpected {lookahead!r} in state {state}")
            if action == "acc":
                return symbol_stack[0]
            if action.startswith("s"):
                state_stack.append(int(action[1:]))
                symbol_stack.append({"name": lookahead, "children": []})
                cursor += 1
                continue
            if action.startswith("r"):
                rule = RULES[int(action[1:])]
                symbols = rule["rule"]
                pop_count = 0 if symbols == ["ε"] else len(symbols)
                children = [symbol_stack.pop() for _ in range(pop_count)][::-1]
                if pop_count:
                    del state_stack[-pop_count:]
                destination = GOTO_TABLE[str(state_stack[-1])].get(rule["variable"])
                if destination is None:
                    raise ValueError(f"Missing GOTO for {rule['variable']}")
                state_stack.append(destination)
                symbol_stack.append({"name": rule["variable"], "children": children})
                continue
            raise ValueError(f"Unknown parser action: {action}")
        raise ValueError("Parse failed: unexpected end of input")

if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(f"Usage: python {sys.argv[0]} '<input>'")
    try:
        print(json.dumps(Parser().parse(sys.argv[1]), indent=2))
    except ValueError as error:
        raise SystemExit(str(error))
`;

    const cppCode = `// Autogenerated ${parserType} Parser
#include <algorithm>
#include <cctype>
#include <iostream>
#include <stdexcept>
#include <string>
#include <unordered_map>
#include <vector>

struct Node {
    std::string name;
    std::vector<Node> children;
};
struct Rule {
    std::string variable;
    std::vector<std::string> symbols;
};
using ActionRow = std::unordered_map<std::string, std::string>;
using GotoRow = std::unordered_map<std::string, int>;

const std::vector<ActionRow> ACTION_TABLE = {
${cppAction}
};
const std::vector<GotoRow> GOTO_TABLE = {
${cppGoto}
};
const std::vector<Rule> RULES = {
${cppRules}
};
const std::vector<std::string> TERMINALS = {${cppTerminals}};

class Parser {
public:
    std::vector<std::string> tokenize(const std::string& text) const {
        auto terminals = TERMINALS;
        std::sort(terminals.begin(), terminals.end(), [](const auto& left, const auto& right) { return left.size() > right.size(); });
        std::vector<std::string> tokens;
        std::size_t cursor = 0;
        while (cursor < text.size()) {
            if (std::isspace(static_cast<unsigned char>(text[cursor]))) { ++cursor; continue; }
            bool matched = false;
            for (const auto& terminal : terminals) {
                if (text.compare(cursor, terminal.size(), terminal) == 0) {
                    tokens.push_back(terminal);
                    cursor += terminal.size();
                    matched = true;
                    break;
                }
            }
            if (!matched) throw std::runtime_error("Lexical error at position " + std::to_string(cursor));
        }
        tokens.push_back("$");
        return tokens;
    }

    Node parse(const std::string& text) const {
        const auto tokens = tokenize(text);
        std::vector<int> states = {0};
        std::vector<Node> symbols;
        std::size_t cursor = 0;
        while (cursor < tokens.size()) {
            const int state = states.back();
            const auto& lookahead = tokens[cursor];
            const auto actionIt = ACTION_TABLE.at(state).find(lookahead);
            if (actionIt == ACTION_TABLE.at(state).end()) throw std::runtime_error("Syntax error: unexpected '" + lookahead + "' in state " + std::to_string(state));
            const auto& action = actionIt->second;
            if (action == "acc") {
                if (symbols.empty()) throw std::runtime_error("Parser accepted without a syntax tree");
                return symbols.front();
            }
            if (action.front() == 's') {
                states.push_back(std::stoi(action.substr(1)));
                symbols.push_back(Node{lookahead, {}});
                ++cursor;
            } else if (action.front() == 'r') {
                const auto& rule = RULES.at(std::stoi(action.substr(1)));
                const std::size_t popCount = rule.symbols == std::vector<std::string>{"ε"} ? 0 : rule.symbols.size();
                std::vector<Node> children(popCount);
                for (std::size_t index = popCount; index > 0; --index) {
                    states.pop_back();
                    children[index - 1] = std::move(symbols.back());
                    symbols.pop_back();
                }
                const auto destination = GOTO_TABLE.at(states.back()).find(rule.variable);
                if (destination == GOTO_TABLE.at(states.back()).end()) throw std::runtime_error("Missing GOTO for " + rule.variable);
                states.push_back(destination->second);
                symbols.push_back(Node{rule.variable, std::move(children)});
            } else {
                throw std::runtime_error("Unknown parser action: " + action);
            }
        }
        throw std::runtime_error("Parse failed: unexpected end of input");
    }
};

void printAst(const Node& node, int depth = 0) {
    std::cout << std::string(static_cast<std::size_t>(depth) * 2, ' ') << node.name << "\\n";
    for (const auto& child : node.children) {
        printAst(child, depth + 1);
    }
}

int main(int argc, char** argv) {
    if (argc != 2) { std::cerr << "Usage: parser '<input>'\\n"; return 2; }
    try {
        Parser parser;
        const auto tree = parser.parse(argv[1]);
        std::cout << "Accepted\\nParse tree:\\n";
        printAst(tree);
    } catch (const std::exception& error) {
        std::cerr << error.what() << "\\n";
        return 1;
    }
}
`;

    return {
        javascript: javascriptCode,
        python: pythonCode,
        cpp: cppCode
    };
};