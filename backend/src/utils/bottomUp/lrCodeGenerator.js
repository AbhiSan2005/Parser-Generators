/**
 * Generates standalone, exportable parser code.
 * Injects the compiled ACTION and GOTO tables directly into a JavaScript script.
 */
export const generateLRCode = (grammar, tableData, parserType) => {
    const { action, goto, indexed_rules } = tableData;

    // Convert matrices to strings for injection
    const actionStr = JSON.stringify(action, null, 4);
    const gotoStr = JSON.stringify(goto, null, 4);
    const rulesStr = JSON.stringify(indexed_rules, null, 4);

    // ==========================================
    // JAVASCRIPT STANDALONE TEMPLATE
    // ==========================================
    const javascriptCode = `// Autogenerated ${parserType} Parser
// Generated by Compiler Playground

const ACTION_TABLE = ${actionStr};
const GOTO_TABLE = ${gotoStr};
const RULES = ${rulesStr};

class Parser {
    constructor(terminals) {
        // Sort terminals by length descending to match longest tokens first
        this.terminals = terminals.sort((a, b) => b.length - a.length);
    }

    tokenize(input) {
        let cursor = 0;
        const tokens = [];
        
        while (cursor < input.length) {
            const char = input[cursor];
            
            // Skip whitespace
            if (/\\s/.test(char)) { 
                cursor++; 
                continue; 
            }
            
            let matched = false;
            for (const t of this.terminals) {
                if (input.startsWith(t, cursor)) {
                    tokens.push(t);
                    cursor += t.length;
                    matched = true;
                    break;
                }
            }
            if (!matched) throw new Error(\`Lexical Error: Unrecognized token at position \${cursor}\`);
        }
        
        tokens.push('$');
        return tokens;
    }

    parse(inputString) {
        const tokens = this.tokenize(inputString);
        const stateStack = [0];
        const symbolStack = [];
        let cursor = 0;

        while (cursor < tokens.length) {
            const state = stateStack[stateStack.length - 1];
            const lookahead = tokens[cursor];
            const action = ACTION_TABLE[state][lookahead];

            if (!action) {
                throw new Error(\`Syntax Error: Unexpected '\${lookahead}' at state \${state}\`);
            }

            if (action === 'acc') {
                console.log("✅ PARSE SUCCESSFUL!");
                return symbolStack[0];
            }

            // Shift
            if (action.startsWith('s')) {
                const nextState = parseInt(action.substring(1), 10);
                stateStack.push(nextState);
                symbolStack.push({ name: lookahead, children: [] });
                cursor++;
            } 
            // Reduce
            else if (action.startsWith('r')) {
                const ruleIdx = parseInt(action.substring(1), 10);
                const rule = RULES[ruleIdx];
                const popCount = rule.rule[0] === 'ε' ? 0 : rule.rule.length;
                
                const children = [];
                for (let i = 0; i < popCount; i++) {
                    stateStack.pop();
                    children.unshift(symbolStack.pop());
                }

                const exposedState = stateStack[stateStack.length - 1];
                const gotoState = GOTO_TABLE[exposedState][rule.variable];
                
                if (gotoState === undefined) {
                    throw new Error(\`GOTO Error: Missing transition for '\${rule.variable}'\`);
                }
                
                stateStack.push(gotoState);
                symbolStack.push({ name: rule.variable, children });
            }
        }
        
        throw new Error("Parse failed: Unexpected end of input.");
    }
}

// ==========================================
// EXAMPLE USAGE:
// Uncomment the lines below to test this file locally using Node.js
// ==========================================
// const parser = new Parser(${JSON.stringify(grammar.terminals)});
// try {
//     const ast = parser.parse("id + id"); // Replace with your test string
//     console.log(JSON.stringify(ast, null, 2));
// } catch (error) {
//     console.error(error.message);
// }
`;

    return {
        javascript: javascriptCode
    };
};